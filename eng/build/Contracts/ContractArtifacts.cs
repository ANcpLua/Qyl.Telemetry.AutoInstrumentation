using System.Text;
using YamlDotNet.Serialization;
using Item = System.Collections.Generic.OrderedDictionary<string, object?>;

namespace Qyl.Build.Contracts;

/// <summary>
/// The three artifacts generated from the resolved contract: the resolved YAML, its JSON schema and
/// the conformance plan. This renderer is their source of truth; the check fails
/// when a committed copy differs from what it renders.
/// </summary>
static class ContractArtifacts
{
    private const string RegenerateCommand = "./eng/build.sh Contracts --write-contracts";

    private static IReadOnlyList<(AbsolutePath Path, string Content)> ExpectedOutputs(Item contract) =>
    [
        (ContractModel.ResolvedContractPath, RenderResolvedYaml(contract)),
        (ContractModel.SchemaPath, RenderSchema()),
        (ContractModel.ConformancePlanPath, RenderConformancePlan(contract)),
    ];

    private static string RenderResolvedYaml(Item contract)
    {
        // YAML 1.1 quoting: the contract sources are read by YAML 1.1 rules, so a string that 1.1 would
        // read as a boolean, number or date (yes, 0755, 2026-10-11) is quoted.
        var serializer = new SerializerBuilder()
            .WithQuotingNecessaryStrings(quoteYaml1_1Strings: true)
            .WithEventEmitter(static next => new QuoteTimestampEmitter(next), static where => where.After<YamlDotNet.Serialization.EventEmitters.TypeAssigningEventEmitter>())
            .DisableAliases()
            .Build();
        var text = serializer.Serialize(contract).Replace("\r\n", "\n", StringComparison.Ordinal);
        if (!text.EndsWith('\n'))
            text += "\n";
        return $"# <auto-generated/>\n# Regenerate with `{RegenerateCommand}`.\n" + text;
    }

    private static string RenderSchema()
    {
        string[] commonRequired =
        [
            "kind", "key", "contract_origin", "status", "index", "contract_item_id", "upstream_sources", "lane", "qyl_status",
            "call_site_visibility", "payload_access", "evidence_level", "primary_owner", "evidence",
        ];
        var total = ContractModel.TotalContractItemCount;
        var schema = new Item
        {
            ["$schema"] = "https://json-schema.org/draft/2020-12/schema",
            ["$id"] = "https://qyl.dev/schemas/qyl-aot-contract.schema.json",
            ["$comment"] = $"<auto-generated/> Regenerate with {RegenerateCommand}.",
            ["type"] = "object",
            ["additionalProperties"] = false,
            ["required"] = List("schema_id", "schema_version", "generated_at", "sources", "generated_from", "contract_items"),
            ["properties"] = new Item
            {
                ["schema_id"] = new Item { ["const"] = "qyl-aot-autoinstrumentation-resolved-contract" },
                ["schema_version"] = new Item { ["const"] = "2.0.0" },
                ["generated_at"] = new Item { ["type"] = "string" },
                ["sources"] = new Item
                {
                    ["type"] = "object",
                    ["additionalProperties"] = false,
                    ["required"] = List(ContractModel.UpstreamOrigin, ContractModel.QylNativeOrigin),
                    ["properties"] = new Item
                    {
                        [ContractModel.UpstreamOrigin] = new Item { ["type"] = "object" },
                        [ContractModel.QylNativeOrigin] = new Item { ["type"] = "object" },
                    },
                },
                ["generated_from"] = new Item
                {
                    ["type"] = "object",
                    ["additionalProperties"] = false,
                    ["required"] = List("upstream_contract", "qyl_native_contract", "qyl_ownership"),
                    ["properties"] = new Item
                    {
                        ["upstream_contract"] = new Item { ["const"] = Repo.Relative(ContractModel.UpstreamContractPath) },
                        ["qyl_native_contract"] = new Item { ["const"] = Repo.Relative(ContractModel.QylNativeContractPath) },
                        ["qyl_ownership"] = new Item { ["const"] = Repo.Relative(ContractModel.OwnershipPath) },
                    },
                },
                ["contract_items"] = new Item
                {
                    ["type"] = "array",
                    ["minItems"] = (long)total,
                    ["maxItems"] = (long)total,
                    ["items"] = new Item { ["$ref"] = "#/$defs/contract_item" },
                },
            },
            ["$defs"] = new Item
            {
                ["contract_item"] = new Item
                {
                    ["oneOf"] = new List<object?>
                    {
                        new Item { ["$ref"] = "#/$defs/signal_item" },
                        new Item { ["$ref"] = "#/$defs/control_item" },
                        new Item { ["$ref"] = "#/$defs/option_item" },
                    },
                },
                ["common_properties"] = CommonSchemaProperties(),
                ["signal_item"] = ItemSchema(ContractModel.SignalKind,
                    [.. commonRequired, "signal", "instrumentation_id", "environment_toggle", "libraries", "supported_versions", "instrumentation_types", "instrumentation_type_operator"],
                    ContractModel.SignalItemProperties),
                ["control_item"] = ItemSchema(ContractModel.ControlKind,
                    [.. commonRequired, "environment_variable", "scope", "description"],
                    ContractModel.ControlItemProperties),
                ["option_item"] = ItemSchema(ContractModel.OptionKind,
                    [.. commonRequired, "environment_variable", "target_signal", "target_instrumentation_id", "description", "attribute_names"],
                    ContractModel.OptionItemProperties),
                ["conformance_signal"] = new Item
                {
                    ["type"] = "object",
                    ["additionalProperties"] = false,
                    ["required"] = List("kind", "name", "required_attributes", "recommended_attributes", "opt_in_attributes"),
                    ["properties"] = new Item
                    {
                        ["kind"] = new Item { ["enum"] = SortedList(ContractModel.ConformanceKinds) },
                        ["name"] = new Item { ["type"] = "string" },
                        ["required_attributes"] = StringArraySchema(),
                        ["recommended_attributes"] = StringArraySchema(),
                        ["opt_in_attributes"] = StringArraySchema(),
                    },
                },
                ["upstream_source"] = new Item
                {
                    ["type"] = "object",
                    ["additionalProperties"] = false,
                    ["required"] = List("label", "url"),
                    ["properties"] = new Item
                    {
                        ["label"] = new Item { ["type"] = "string", ["minLength"] = 1L },
                        ["url"] = new Item { ["type"] = "string", ["pattern"] = "^https?://" },
                    },
                },
            },
            ["allOf"] = new List<object?>
            {
                new Item
                {
                    ["if"] = new Item { ["properties"] = new Item { ["contract_items"] = new Item { ["contains"] = new Item { ["properties"] = new Item { ["lane"] = new Item { ["const"] = "runtime_public_telemetry" } } } } } },
                    ["then"] = new Item
                    {
                        ["properties"] = new Item
                        {
                            ["contract_items"] = new Item
                            {
                                ["items"] = new Item
                                {
                                    ["if"] = new Item { ["properties"] = new Item { ["lane"] = new Item { ["const"] = "runtime_public_telemetry" } } },
                                    ["then"] = new Item { ["properties"] = new Item { ["payload_access"] = new Item { ["enum"] = List("aot_reflection", "typed_public") } } },
                                },
                            },
                        },
                    },
                },
            },
        };
        return Yaml.ToJson(schema);
    }

    private static Item CommonSchemaProperties() => new()
    {
        ["kind"] = new Item { ["enum"] = List(ContractModel.SignalKind, ContractModel.ControlKind, ContractModel.OptionKind) },
        ["key"] = new Item { ["type"] = "string" },
        ["contract_origin"] = new Item { ["enum"] = List(ContractModel.UpstreamOrigin, ContractModel.QylNativeOrigin) },
        ["status"] = new Item { ["type"] = "string" },
        ["index"] = new Item { ["type"] = "integer", ["minimum"] = 1L, ["maximum"] = (long)ContractModel.TotalContractItemCount },
        ["contract_item_id"] = new Item
        {
            ["type"] = "string",
            ["pattern"] = "^(?:OTEL_DOTNET_AUTO_CONTRACT|QYL_NATIVE_CONTRACT)_[0-9]{3}$",
        },
        ["upstream_sources"] = new Item { ["type"] = "array", ["minItems"] = 1L, ["items"] = new Item { ["$ref"] = "#/$defs/upstream_source" } },
        ["lane"] = new Item { ["enum"] = SortedList(ContractModel.Lanes) },
        ["qyl_status"] = new Item { ["enum"] = SortedList(ContractModel.Statuses) },
        ["call_site_visibility"] = new Item { ["enum"] = SortedList(ContractModel.CallSiteVisibilities) },
        ["payload_access"] = new Item { ["enum"] = SortedList(ContractModel.PayloadAccessValues) },
        ["evidence_level"] = new Item { ["enum"] = SortedList(ContractModel.EvidenceLevels) },
        ["primary_owner"] = new Item { ["type"] = "string" },
        ["evidence"] = StringArraySchema(),
        ["conformance_signals"] = new Item { ["type"] = "array", ["items"] = new Item { ["$ref"] = "#/$defs/conformance_signal" } },
        ["unsupported_reason"] = new Item { ["type"] = "string", ["minLength"] = 1L },
    };

    private static Item ItemSchema(string kind, string[] required, IEnumerable<string> allowedProperties)
    {
        var properties = CommonSchemaProperties();
        var overrides = new Item
        {
            ["kind"] = new Item { ["const"] = kind },
            ["signal"] = new Item { ["enum"] = List("traces", "metrics", "logs") },
            ["instrumentation_id"] = new Item { ["type"] = "string" },
            ["environment_toggle"] = new Item { ["type"] = "string" },
            ["environment_toggle_origin"] = new Item { ["type"] = "string" },
            ["libraries"] = new Item { ["type"] = "array" },
            ["supported_versions"] = new Item { ["type"] = "string" },
            ["instrumentation_types"] = StringArraySchema(),
            ["instrumentation_type_operator"] = new Item { ["type"] = "string" },
            ["not_supported_on"] = StringArraySchema(),
            ["notes"] = StringArraySchema(),
            ["documentation"] = new Item { ["type"] = "object" },
            ["upstream_sources"] = new Item { ["type"] = "array", ["minItems"] = 1L, ["items"] = new Item { ["$ref"] = "#/$defs/upstream_source" } },
            ["environment_variable"] = new Item { ["type"] = "string" },
            ["scope"] = new Item { ["type"] = "string" },
            ["description"] = new Item { ["type"] = "string" },
            ["default_value"] = new Item(),
            ["overrides"] = StringArraySchema(),
            ["is_pattern"] = new Item { ["type"] = "boolean" },
            ["placeholder"] = new Item { ["type"] = "string" },
            ["target_signal"] = new Item { ["enum"] = List("traces", "metrics", "logs") },
            ["target_instrumentation_id"] = new Item { ["type"] = "string" },
            ["attribute_names"] = StringArraySchema(),
            ["default_behavior"] = new Item { ["type"] = "string" },
            ["value_format"] = new Item { ["type"] = "string" },
            ["value_type"] = new Item { ["type"] = "string" },
        };
        foreach (var (key, value) in overrides)
            properties[key] = value;

        var selected = new Item();
        foreach (var key in allowedProperties.Sorted())
            selected[key] = properties[key];

        return new Item
        {
            ["type"] = "object",
            ["additionalProperties"] = false,
            ["required"] = required.Cast<object?>().ToList(),
            ["properties"] = selected,
            ["allOf"] = new List<object?>
            {
                IfThen(new Item { ["lane"] = new Item { ["const"] = "runtime_public_telemetry" } },
                    new Item { ["properties"] = new Item { ["payload_access"] = new Item { ["enum"] = List("aot_reflection", "typed_public") } } }),
                IfThen(new Item { ["payload_access"] = new Item { ["const"] = "aot_reflection" } },
                    new Item { ["properties"] = new Item { ["evidence_level"] = new Item { ["const"] = "verified_nativeaot" } } }),
                IfThen(new Item { ["call_site_visibility"] = new Item { ["const"] = "library_internal" } },
                    new Item { ["not"] = new Item { ["properties"] = new Item { ["lane"] = new Item { ["const"] = "source_interceptor" } } } }),
                IfThen(new Item { ["payload_access"] = new Item { ["const"] = "reflection_required" } },
                    new Item { ["not"] = new Item { ["properties"] = new Item { ["qyl_status"] = new Item { ["const"] = "implemented" } } } }),
            },
        };
    }

    private static Item IfThen(Item condition, Item then) => new()
    {
        ["if"] = new Item { ["properties"] = condition },
        ["then"] = then,
    };

    private static Item StringArraySchema() => new() { ["type"] = "array", ["items"] = new Item { ["type"] = "string" } };

    private static List<object?> List(params string[] values) => values.Cast<object?>().ToList();

    private static List<object?> SortedList(IEnumerable<string> values) => values.Sorted().Cast<object?>().ToList();

    private static string RenderConformancePlan(Item contract)
    {
        var signalsByName = new Dictionary<string, Item>(StringComparer.Ordinal);
        foreach (var signal in ContractModel.ConformanceSignalsForPlan(contract))
            signalsByName[ContractValue.Text(signal["name"])] = signal;

        var services = new List<object?>();
        foreach (var profile in ContractModel.ConformanceProfiles)
        {
            var expectedSignals = new List<object?>();
            foreach (var name in profile.SignalNames)
            {
                var signal = signalsByName[name];
                expectedSignals.Add(new Item
                {
                    ["kind"] = ContractValue.Text(signal["kind"]),
                    ["name"] = ContractValue.Text(signal["name"]),
                    ["required_attributes"] = ContractModel.Strings(signal["required_attributes"]).Cast<object?>().ToList(),
                    ["recommended_attributes"] = ContractModel.Strings(signal["recommended_attributes"]).Cast<object?>().ToList(),
                    ["opt_in_attributes"] = ContractModel.Strings(signal["opt_in_attributes"]).Cast<object?>().ToList(),
                });
            }

            services.Add(new Item
            {
                ["service_name"] = profile.ServiceName,
                ["profile_id"] = profile.ProfileId,
                ["expected_signals"] = expectedSignals,
            });
        }

        return Yaml.ToJson(new Item
        {
            ["schema_version"] = "1",
            ["graph_schema_version"] = "1",
            ["services"] = services,
        });
    }

    public static void VerifyGeneratedFiles(Item contract)
    {
        var mismatches = new List<string>();
        foreach (var (path, expected) in ExpectedOutputs(contract))
        {
            if (!path.FileExists())
            {
                mismatches.Add($"missing generated artifact: {Repo.Relative(path)}");
                continue;
            }

            var actual = File.ReadAllText(path);
            if (actual != expected)
                mismatches.Add($"stale generated artifact: {Repo.Relative(path)}\n{DiffExcerpt(actual, expected, Repo.Relative(path))}");
        }

        Gate.Require(mismatches.Count == 0, () => string.Join("\n", mismatches) + $"\nrun: {RegenerateCommand}");
    }

    public static void WriteGeneratedFiles(Item contract)
    {
        foreach (var (path, content) in ExpectedOutputs(contract))
        {
            path.Parent.CreateDirectory();
            File.WriteAllText(path, content, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
        }
    }

    /// <summary>The region around the first differing line, unified-diff style, capped at 4000 characters.</summary>
    private static string DiffExcerpt(string actual, string expected, string name)
    {
        var a = actual.Split('\n');
        var b = expected.Split('\n');
        var first = 0;
        while (first < a.Length && first < b.Length && a[first] == b[first])
            first++;
        var tailA = a.Length - 1;
        var tailB = b.Length - 1;
        while (tailA >= first && tailB >= first && a[tailA] == b[tailB])
        {
            tailA--;
            tailB--;
        }

        var start = Math.Max(0, first - 3);
        var text = new StringBuilder()
            .AppendLine($"--- {name}")
            .AppendLine($"+++ {name} (generated)")
            .AppendLine($"@@ -{start + 1},{tailA - start + 4} +{start + 1},{tailB - start + 4} @@");
        for (var index = start; index < first; index++)
            text.Append(' ').AppendLine(a[index]);
        for (var index = first; index <= tailA; index++)
            text.Append('-').AppendLine(a[index]);
        for (var index = first; index <= tailB; index++)
            text.Append('+').AppendLine(b[index]);
        for (var index = tailA + 1; index < Math.Min(a.Length, tailA + 4); index++)
            text.Append(' ').AppendLine(a[index]);
        var excerpt = text.ToString();
        return excerpt.Length > 4000 ? excerpt[..4000] : excerpt;
    }
}

/// <summary>Quotes a plain string scalar that YAML 1.1 would read as a timestamp (YamlDotNet's
/// YAML 1.1 quoting covers booleans and numbers but not dates) and spells null out.</summary>
sealed partial class QuoteTimestampEmitter(IEventEmitter next) : YamlDotNet.Serialization.EventEmitters.ChainedEventEmitter(next)
{
    public override void Emit(ScalarEventInfo eventInfo, YamlDotNet.Core.IEmitter emitter)
    {
        if (eventInfo.Source.Value is string text && Timestamp().IsMatch(text))
            eventInfo.Style = YamlDotNet.Core.ScalarStyle.SingleQuoted;
        // A null renders as "null", never as an empty value that leaves trailing whitespace behind.
        if (eventInfo.Source.Value is null)
            eventInfo.RenderedValue = "null";
        base.Emit(eventInfo, emitter);
    }

    [System.Text.RegularExpressions.GeneratedRegex(@"^\d{4}-\d{1,2}-\d{1,2}(?:[Tt ].*)?$")]
    private static partial System.Text.RegularExpressions.Regex Timestamp();
}
