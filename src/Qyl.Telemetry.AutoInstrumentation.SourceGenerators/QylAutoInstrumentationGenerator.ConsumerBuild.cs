using ANcpLua.Roslyn.Utilities;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;

namespace Qyl.Telemetry.AutoInstrumentation.SourceGenerators;

/// <summary>
/// <c>QylConsumerBuild</c>: the consuming build's version and source revision as constants, read from
/// the compiler-visible <c>InformationalVersion</c> and <c>SourceRevisionId</c> the package's build
/// assets expose. Its module initializer hands the version to the qyl runtime, so <c>AddQyl</c> stamps
/// <c>service.version</c> without reflection and without the application typing it.
/// </summary>
/// <remarks>
/// Only an executable gets it: the process is the service, and a library's version is not the
/// service's. The qyl runtime assemblies themselves are excluded.
/// </remarks>
public sealed partial class QylAutoInstrumentationGenerator
{
    private const string InformationalVersionProperty = "build_property.InformationalVersion";
    private const string SourceRevisionIdProperty = "build_property.SourceRevisionId";

    /// <summary>The service version (the informational version, carrying the revision as SemVer build
    /// metadata) and the bare source revision.</summary>
    private readonly record struct ConsumerBuild(string Version, string Revision);

    private static bool IsConsumerExecutable(Compilation compilation)
        => compilation.Options.OutputKind is OutputKind.ConsoleApplication or OutputKind.WindowsApplication or OutputKind.WindowsRuntimeApplication
           && !(compilation.AssemblyName is { } assemblyName && QylRuntimeAssemblies.Contains(assemblyName));

    private static ConsumerBuild? ReadConsumerBuild(AnalyzerConfigOptions options)
    {
        var informational = options.TryGetValue(InformationalVersionProperty, out var value) ? value.Trim() : string.Empty;
        var revision = options.TryGetValue(SourceRevisionIdProperty, out value) ? value.Trim() : string.Empty;
        if (informational.Length is 0)
            return null;

        // The SDK appends the revision to the informational version itself; a build that set its own
        // informational version gets it appended here by the same SemVer rule.
        var version = revision.Length is 0 || informational.IndexOfOrdinal(revision) >= 0
            ? informational
            : informational + (informational.IndexOf('+') >= 0 ? "." : "+") + revision;
        return new ConsumerBuild(version, revision);
    }

    private static void EmitConsumerBuild(SourceProductionContext context, ConsumerBuild? build)
    {
        if (build is not { } consumer)
            return;

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("namespace Qyl.Telemetry.AutoInstrumentation.Generated");
        builder.AppendLine("{");
        builder.AppendLine("    /// <summary>This build's version and source revision, as constants.</summary>");
        builder.AppendLine("    internal static class QylConsumerBuild");
        builder.AppendLine("    {");
        builder.AppendLine("        private const int RequiredQylGeneratedCodeAbi = global::Qyl.Telemetry.AutoInstrumentation.GeneratedCode.QylGeneratedCodeAbi.V28;");
        builder.AppendLine();
        builder.AppendLine("        /// <summary>The informational version, carrying the source revision as SemVer build metadata: the service.version AddQyl stamps.</summary>");
        builder.Append("        public const string Version = ");
        AppendStringLiteral(builder, consumer.Version);
        builder.AppendLine(";");
        builder.AppendLine();
        builder.AppendLine("        /// <summary>The source revision; empty outside source control.</summary>");
        builder.Append("        public const string Revision = ");
        AppendStringLiteral(builder, consumer.Revision);
        builder.AppendLine(";");
        builder.AppendLine();
        builder.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
        builder.AppendLine("        internal static void Register()");
        builder.AppendLine("            => global::Qyl.Telemetry.AutoInstrumentation.GeneratedCode.QylConsumerBuildInfo.Register(Version);");
        builder.AppendLine("    }");
        builder.AppendLine("}");

        context.AddSource("QylConsumerBuild.g.cs", SourceText.From(builder.ToString(), Encoding.UTF8));
    }
}
